import { writeFile } from "node:fs/promises";

const endpoint = "https://geo.abs.gov.au/arcgis/rest/services/ASGS2021/SAL/MapServer/0/query";
const pageSize = 2000;
const rows = [];

for (let offset = 0; ; offset += pageSize) {
    const params = new URLSearchParams({
        where: "1=1",
        outFields: "sal_code_2021,sal_name_2021,state_code_2021,state_name_2021",
        returnGeometry: "false",
        orderByFields: "sal_code_2021",
        resultOffset: String(offset),
        resultRecordCount: String(pageSize),
        f: "json",
    });
    const response = await fetch(`${endpoint}?${params}`);
    if (!response.ok) throw new Error(`ABS request failed with ${response.status}`);
    const payload = await response.json();
    if (payload.error) throw new Error(payload.error.message || "ABS request failed");
    const page = payload.features.map(({ attributes }) => attributes);
    rows.push(...page);
    if (page.length < pageSize) break;
}

const specialNames = /^(Migratory|No usual address|Outside Australia)/i;
const stateCodes = { "1": "NSW", "2": "VIC", "3": "QLD", "4": "SA", "5": "WA", "6": "TAS", "7": "NT", "8": "ACT", "9": "OT" };
const places = rows
    .filter(row => row.sal_name_2021 && !specialNames.test(row.sal_name_2021))
    .map(row => [row.sal_name_2021, stateCodes[row.state_code_2021] || row.state_code_2021]);

const source = `// Generated by scripts/sync-australian-places.mjs from the ABS ASGS 2021 SAL service.\n` +
`// Do not hand-edit. Refresh from the official source with: pnpm places:sync\n` +
`export type AustralianPlace = readonly [name: string, stateCode: string];\n` +
`export const australianPlaceSource = ${JSON.stringify({
    title: "Australian Statistical Geography Standard (ASGS) Edition 3 — Suburbs and Localities, 2021",
    url: "https://www.abs.gov.au/statistics/standards/australian-statistical-geography-standard-asgs/edition-3-july-2021-june-2026/non-abs-structures/suburbs-and-localities",
    service: endpoint,
    retrievedAt: new Date().toISOString(),
    licence: "Creative Commons Attribution 4.0 International",
    count: places.length,
}, null, 2)} as const;\n` +
`export const australianPlaces: readonly AustralianPlace[] = ${JSON.stringify(places)};\n`;

await writeFile(new URL("../app/australian-places.ts", import.meta.url), source, "utf8");
console.log(`Wrote ${places.length.toLocaleString("en-AU")} Australian suburbs and localities.`);
